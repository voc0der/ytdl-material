import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { runInNewContext } from 'node:vm';

const root = new URL('../../', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');

// Read source constants without loading the backend, its dependencies, or local config.
const registrySource = read('backend/consts.js');
const registry = runInNewContext(`${registrySource}\nexports.CONFIG_ITEMS`, { exports: {} }, { timeout: 1000 });
const defaultsSource = read('backend/config.js').match(/const DEFAULT_CONFIG = (\{[\s\S]*?\n  \})\s*\n/);
if (!defaultsSource) throw new Error('Could not locate DEFAULT_CONFIG; update the docs extractor.');
const defaults = runInNewContext(`(${defaultsSource[1]})`, {}, { timeout: 1000 });

const code = value => `<code>${String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('|', '&#124;')}</code>`;
const groups = new Map();
for (const [name, setting] of Object.entries(registry)) {
  const [, group, ...path] = setting.path.split('.');
  const value = setting.path.split('.').reduce((parent, key) => parent?.[key], defaults);
  if (!groups.has(group)) groups.set(group, []);
  groups.get(group).push(`| ${code(name)} | ${code(path.join('.'))} | ${value === undefined ? 'Not set' : code(JSON.stringify(value))} |`);
}

const sections = [...groups].map(([group, rows]) => `## ${group}\n\nJSON section: ${code(`YtdlMaterial.${group}`)}\n\n| Environment variable | JSON field | Source default |\n| --- | --- | --- |\n${rows.join('\n')}\n`);
const output = `<!-- Generated by node dev/docs/config-reference.mjs. Edit backend defaults or the generator. -->
# Configuration defaults

This table is generated from the setting registry in [backend/consts.js](https://github.com/voc0der/ytdl-material/blob/main/backend/consts.js) and the source defaults in [backend/config.js](https://github.com/voc0der/ytdl-material/blob/main/backend/config.js). It does not read a running instance's configuration or secrets.

These are defaults for an unconfigured app. Docker Compose overrides database settings, and existing installations retain saved values. Enabling optional impersonation dependencies also changes the default for new configurations. A registered variable with **Not set** has no value in the source defaults.

See [environment variables](environment.md) for startup-only controls, [configuration](../getting-started/configuration.md) for precedence and restart behavior, and the deployment guides before changing database or authentication settings. Object and array values belong in the UI or JSON file; environment strings are not generally parsed as JSON.

${sections.join('\n')}`;

const destination = new URL('docs/reference/configuration.md', root);
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output) {
    throw new Error('Configuration reference is stale. Run node dev/docs/config-reference.mjs.');
  }
  console.log(`Configuration reference matches ${Object.keys(registry).length} registered settings.`);
} else {
  writeFileSync(destination, output);
  console.log(`Wrote ${fileURLToPath(destination)} (${Object.keys(registry).length} settings).`);
}
